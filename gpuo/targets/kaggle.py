"""Kaggle target, using the official Kaggle CLI (`pip install kaggle`).

Rules this adapter enforces:
  * One Kaggle target per owner (also enforced by a unique index in the DB).
  * Kernels are always private: the launcher refers to storage credentials.
  * No secrets are written into the kernel source. Storage credentials are read inside the
    kernel from Kaggle Secrets (Add-ons -> Secrets in the Kaggle editor) under the names
    GPUO_S3_KEY_ID, GPUO_S3_SECRET, and optionally GPUO_S3_ENDPOINT.
  * The Kaggle API token stays where the Kaggle CLI keeps it (~/.kaggle/kaggle.json or the
    KAGGLE_API_TOKEN / KAGGLE_USERNAME+KAGGLE_KEY env vars). gpuo never stores it.

One Kaggle kernel per job; each segment pushes a new version of that kernel.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from .base import ProviderStatus, register

LAUNCHER = """\
# Generated by gpuo. Runs one training segment, then exits.
import os, subprocess, sys

ENV = {env_json}

try:
    from kaggle_secrets import UserSecretsClient
    _s = UserSecretsClient()
    for name, var in [("GPUO_S3_KEY_ID", "AWS_ACCESS_KEY_ID"),
                      ("GPUO_S3_SECRET", "AWS_SECRET_ACCESS_KEY"),
                      ("GPUO_S3_ENDPOINT", "GPUO_S3_ENDPOINT")]:
        try:
            os.environ[var] = _s.get_secret(name)
        except Exception:
            pass
except ImportError:
    pass

os.environ.update(ENV)
subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", {pip_spec!r}, "boto3"])
sys.exit(subprocess.call([sys.executable, "-m", "gpuo.agent", "--workdir", "/kaggle/working/gpuo"]))
"""


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")[:50]


def _kaggle_cli() -> str:
    exe = shutil.which("kaggle")
    if not exe:
        raise RuntimeError("Kaggle CLI not found. Install it with: pip install 'gpuo[kaggle]'")
    return exe


class KaggleTarget:
    kind = "kaggle"

    def kernel_ref(self, target: dict[str, Any], job: dict[str, Any]) -> str:
        user = target["settings"]["username"]
        return f"{user}/{_slug('gpuo-' + job['id'])}"

    def launch(self, target: dict[str, Any], job: dict[str, Any], env: dict[str, str]) -> str:
        if not env["GPUO_STORAGE"].startswith("s3://"):
            raise RuntimeError(
                "Kaggle targets need s3:// storage (S3 or Cloudflare R2): a Kaggle kernel "
                "cannot read a folder on your computer."
            )
        s = target["settings"]
        ref = self.kernel_ref(target, job)
        safe_env = {k: v for k, v in env.items() if k.startswith("GPUO_") and k != "GPUO_HOME"}
        meta = {
            "id": ref,
            "title": ref.split("/", 1)[1],
            "code_file": "run.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": bool(s.get("enable_gpu", True)),
            "enable_internet": True,
            "dataset_sources": job["config"].get("kaggle_datasets", []),
            "competition_sources": [],
            "kernel_sources": [],
        }
        meta.update(s.get("extra_metadata", {}))
        meta["is_private"] = True  # never overridable
        with tempfile.TemporaryDirectory() as d:
            Path(d, "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
            Path(d, "run.py").write_text(
                LAUNCHER.format(env_json=json.dumps(safe_env, indent=2), pip_spec=s.get("pip_spec", "gpuo"))
            )
            out = subprocess.run(
                [_kaggle_cli(), "kernels", "push", "-p", d],
                capture_output=True,
                text=True,
                timeout=300,
            )
        text = (out.stdout + out.stderr).strip()
        if out.returncode != 0 or "error" in text.lower() and "successfully" not in text.lower():
            raise RuntimeError(f"kaggle kernels push failed: {text}")
        return ref

    def status(self, target: dict[str, Any], handle: str) -> ProviderStatus:
        try:
            out = subprocess.run(
                [_kaggle_cli(), "kernels", "status", handle],
                capture_output=True,
                text=True,
                timeout=60,
            )
        except (subprocess.TimeoutExpired, RuntimeError):
            return ProviderStatus.UNKNOWN
        text = (out.stdout + out.stderr).lower()
        if out.returncode != 0:
            return ProviderStatus.UNKNOWN
        if "queued" in text:
            return ProviderStatus.QUEUED
        if "running" in text:
            return ProviderStatus.RUNNING
        if "complete" in text:
            return ProviderStatus.EXITED
        if "error" in text or "cancel" in text:
            return ProviderStatus.ERROR
        return ProviderStatus.UNKNOWN

    def cancel(self, target: dict[str, Any], handle: str) -> None:
        # The Kaggle CLI has no documented cancel command; the agent stops itself when its
        # lease is revoked (it checks the lease before every checkpoint).
        return None

    def output(self, handle: str, dest: str) -> str:
        out = subprocess.run(
            [_kaggle_cli(), "kernels", "output", handle, "-p", dest],
            capture_output=True,
            text=True,
            timeout=600,
        )
        return out.stdout + out.stderr


register(KaggleTarget())
